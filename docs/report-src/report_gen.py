TITLE_MODE = [False]
def para(text='', align=None, indent=True, bold=False, italic=False, size=14, space_after=0, keep_with_next=False):
    p = doc.add_paragraph()
    if TITLE_MODE[0]: p.paragraph_format.line_spacing = 1.15
    if align is not None: p.alignment = align
    if not indent: p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_after = Pt(space_after)
    if keep_with_next: p.paragraph_format.keep_with_next = True
    if text:
        r = p.add_run(text); set_font(r, size=size, bold=bold, italic=italic)
    return p

def add_runs(p, parts):
    """parts: список (текст, bold)"""
    for text, bold in parts:
        r = p.add_run(text); set_font(r, bold=bold)

