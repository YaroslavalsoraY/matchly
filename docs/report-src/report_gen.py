def set_cell(cell, text, size=12, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, italic=False):
    cell.text = ''
    p = cell.paragraphs[0]; p.alignment = align
    p.paragraph_format.first_line_indent = Cm(0); p.paragraph_format.line_spacing = 1.0
    lines = str(text).split('\n')
    for i, line in enumerate(lines):
        if i: p = cell.add_paragraph(); p.alignment = align; p.paragraph_format.first_line_indent = Cm(0); p.paragraph_format.line_spacing = 1.0
        r = p.add_run(line); set_font(r, size=size, bold=bold, italic=italic)

def table(headers, rows, widths=None, size=12, caption=None, header_bold=True):
    if caption:
        cp = para(caption, align=WD_ALIGN_PARAGRAPH.LEFT, indent=False, keep_with_next=True)
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        set_cell(t.rows[0].cells[i], h, size=size, bold=header_bold, align=WD_ALIGN_PARAGRAPH.CENTER)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            set_cell(cells[i], v, size=size)
    if widths:
        t.autofit = False
        tblPr = t._tbl.tblPr
        layout = OxmlElement('w:tblLayout'); layout.set(qn('w:type'), 'fixed'); tblPr.append(layout)
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    # повтор заголовка на новой странице
    trPr = t.rows[0]._tr.get_or_add_trPr(); el = OxmlElement('w:tblHeader'); el.set(qn('w:val'), 'true'); trPr.append(el)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t

def figure(path, caption, width_cm=16, crop_height=None):
    from PIL import Image
    src = path
    if crop_height:
        im = Image.open(path)
        if im.size[1] > crop_height:
            im = im.crop((0, 0, im.size[0], crop_height)); src = path + '.crop.png'; im.save(src)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(src, width=Cm(width_cm))
    para(caption, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, space_after=12)

def code_block(path=None, text=None, max_lines=None):
    if path: text = open(path, encoding='utf-8').read()
    lines = text.rstrip('\n').split('\n')
    if max_lines: lines = lines[:max_lines]
    for line in lines:
        p = doc.add_paragraph(); p.paragraph_format.first_line_indent = Cm(0); p.paragraph_format.line_spacing = 1.0
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        r = p.add_run(line.replace('\t', '    ') or ' '); set_font(r, name='Courier New', size=9)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)

def add_page_number(paragraph):
    r = paragraph.add_run(); set_font(r, size=12)
    begin = OxmlElement('w:fldChar'); begin.set(qn('w:fldCharType'), 'begin'); r._r.append(begin)
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve'); instr.text = 'PAGE'; r._r.append(instr)
    end = OxmlElement('w:fldChar'); end.set(qn('w:fldCharType'), 'end'); r._r.append(end)

